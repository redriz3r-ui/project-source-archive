from __future__ import annotations

import math
import textwrap
from pathlib import Path
from typing import Any, Iterable


MIN_CUE_SECONDS = 0.75
CAPTION_LINE_CHARS = 34
CAPTION_MAX_LINES = 2


def _finite(value: Any) -> float | None:
    try:
        number = float(value)
    except (TypeError, ValueError):
        return None
    return number if math.isfinite(number) else None


def _readable_text(value: Any) -> str:
    text = " ".join(str(value or "").replace("\x00", " ").split()).strip()
    if not text:
        return ""
    lines = textwrap.wrap(
        text,
        width=CAPTION_LINE_CHARS,
        break_long_words=True,
        break_on_hyphens=False,
        max_lines=CAPTION_MAX_LINES,
        placeholder="…",
    )
    return "\n".join(lines)


def extract_clip_captions(transcript_segments: Iterable[dict] | None,
                          clip_start: float, clip_end: float) -> list[dict]:
    """Return readable, clip-relative cues from overlapping raw transcript units.

    Display times are clamped to the clip. Very short cues are extended toward
    750 ms when the clip boundary and the next cue leave enough room.
    """
    start = _finite(clip_start)
    end = _finite(clip_end)
    if start is None or end is None or start < 0 or end <= start:
        raise ValueError("Clip caption bounds must be finite with end after start.")

    clip_duration = end - start
    cues = []
    for order, segment in enumerate(transcript_segments or []):
        if not isinstance(segment, dict):
            continue
        source_start = _finite(segment.get("start"))
        source_end = _finite(segment.get("end"))
        text = _readable_text(segment.get("text"))
        if (source_start is None or source_end is None or source_end <= source_start
                or not text or source_start >= end or source_end <= start):
            continue
        clamped_start = max(start, source_start)
        clamped_end = min(end, source_end)
        if clamped_end <= clamped_start:
            continue
        cues.append({
            "start": clamped_start - start,
            "end": clamped_end - start,
            "source_start": clamped_start,
            "source_end": clamped_end,
            "text": text,
            "_order": order,
        })

    cues.sort(key=lambda cue: (cue["start"], cue["end"], cue["_order"]))
    rendered = []
    for index, cue in enumerate(cues):
        cue_start = float(cue["start"])
        cue_end = min(clip_duration, float(cue["end"]))
        next_start = float(cues[index + 1]["start"]) if index + 1 < len(cues) else clip_duration

        # Never make an existing overlap worse, and cap normal cues at the next
        # cue so captions do not stack on top of one another.
        if next_start > cue_start:
            cue_end = min(cue_end, next_start)
            extension_limit = min(clip_duration, next_start)
        else:
            extension_limit = cue_end
        if cue_end - cue_start < MIN_CUE_SECONDS:
            cue_end = max(cue_end, min(cue_start + MIN_CUE_SECONDS, extension_limit))
        if cue_end <= cue_start:
            continue

        relative_start = round(cue_start, 3)
        relative_end = round(cue_end, 3)
        rendered.append({
            "start": relative_start,
            "end": relative_end,
            "source_start": round(start + cue_start, 3),
            "source_end": round(start + cue_end, 3),
            "text": cue["text"],
        })
    return rendered


def _ass_timestamp(seconds: float) -> str:
    centiseconds = max(0, round(float(seconds) * 100))
    hours, remainder = divmod(centiseconds, 360_000)
    minutes, remainder = divmod(remainder, 6_000)
    secs, hundredths = divmod(remainder, 100)
    return f"{hours}:{minutes:02d}:{secs:02d}.{hundredths:02d}"


def _ass_text(value: Any) -> str:
    # ASS override blocks use braces, while \N/\n/\h are active escapes. Use
    # visible full-width equivalents for user-supplied control characters, then
    # add only the line breaks generated by our wrapping code.
    text = str(value or "").replace("\\", "＼").replace("{", "｛").replace("}", "｝")
    return r"\N".join(" ".join(line.split()) for line in text.splitlines())


def write_ass_captions(cues: Iterable[dict], destination: Path) -> Path:
    """Write safe 1080x1920 ASS captions for FFmpeg/libass."""
    destination = Path(destination)
    header = """[Script Info]
ScriptType: v4.00+
PlayResX: 1080
PlayResY: 1920
WrapStyle: 2
ScaledBorderAndShadow: yes

[V4+ Styles]
Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding
Style: FFS Captions,Arial,64,&H00FFFFFF,&H00FFFFFF,&H70000000,&H70000000,-1,0,0,0,100,100,0,0,3,4,0,2,70,70,320,1

[Events]
Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text
"""
    events = []
    for cue in cues:
        cue_start = max(0.0, float(cue["start"]))
        cue_end = max(cue_start + 0.01, float(cue["end"]))
        events.append(
            f"Dialogue: 0,{_ass_timestamp(cue_start)},{_ass_timestamp(cue_end)},"
            f"FFS Captions,,0,0,0,,{_ass_text(cue.get('text'))}"
        )
    destination.write_text(header + "\n".join(events) + ("\n" if events else ""), encoding="utf-8")
    return destination


