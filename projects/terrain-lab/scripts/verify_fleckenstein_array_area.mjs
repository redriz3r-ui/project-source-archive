import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import { analyzeArrayArea } from './fleckenstein_array_area.mjs';
import { fleckensteinStudy } from '../src/data/fleckensteinStudy.ts';
import { compute } from '../src/sandbox/analysis.ts';
import { inspectGeoJson } from '../src/sandbox/geojson.ts';

assert.equal(globalThis.document, undefined);
assert.equal(globalThis.window, undefined);
const output = await analyzeArrayArea();
const inspected = inspectGeoJson(output);
assert.equal(inspected.featureCount, 2);
assert.deepEqual(inspected.kinds, ['Polygon']);
const [source, derived] = output.features;
assert.equal(source.id, 400038);
assert.equal(source.properties.case_id, 400038);
assert.equal(source.properties.p_name, 'CalRenew-1');
assert.equal(source.properties.p_state, 'CA');
assert.equal(source.properties.p_area, 161468);
assert.equal(source.properties.terrainLabRole, 'observed solar infrastructure; not tortoise observations');
assert.equal(derived.properties.classification, 'computed geometry');
assert.equal(derived.properties.observed, false);
assert.equal(derived.properties.operation, 'area');
assert.equal(derived.properties.unit, 'square meters');
assert.equal(derived.properties.contractVersion, 'terrain-lab-operation/v1');
assert.equal(derived.properties.sourceVerification, 'registered-dataset');
assert.equal(derived.properties.studyId, fleckensteinStudy.id);
assert.equal(derived.properties.datasetId, 'uspvdb-v1-study-states');
assert.equal(derived.properties.sourceFeatureId, 400038);
assert.match(derived.properties.sourceArchiveSha256, /^[a-f0-9]{64}$/);
assert.match(derived.properties.preparedGeoJsonSha256, /^[a-f0-9]{64}$/);
assert.deepEqual(derived.geometry, source.geometry);
assert.ok(Math.abs(derived.properties.value - 161416.3487055702) < 0.01);
assert.equal(derived.properties.sourceAreaSquareMeters, 161468);
assert.ok(Math.abs(derived.properties.differenceFromSourceAreaSquareMeters) < 100);
const browser = await compute('area', { key: 'uspvdb:400038', label: 'CalRenew-1 · USPVDB case 400038', feature: source });
assert.equal(browser.feature.properties.value, derived.properties.value);
const saved = JSON.parse(readFileSync(new URL('../public/data/fleckenstein-2025/case-400038-area.geojson', import.meta.url)));
assert.deepEqual(saved.features[0], source);
assert.deepEqual(saved.features[1].geometry, derived.geometry);
assert.equal(saved.features[1].properties.value, derived.properties.value);
assert.equal(saved.features[1].properties.sourceVerification, 'registered-dataset');
const run = (...args) => spawnSync(process.execPath, ['--experimental-strip-types', 'scripts/fleckenstein_array_area.mjs', ...args], { encoding: 'utf8' });
const success = run();
assert.equal(success.status, 0, success.stderr);
assert.equal(JSON.parse(success.stdout).features[1].properties.value, derived.properties.value);
const failure = run('--output');
assert.equal(failure.status, 1);
assert.match(failure.stderr, /Usage:/);
console.log('Fleckenstein area workflow passed: checksummed source, headless/browser parity, source-area comparison, saved GeoJSON, provenance, and CLI.');
